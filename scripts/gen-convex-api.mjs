// Writes convex/_generated/api.d.ts in the same shape `npx convex codegen` produces, without contacting a deployment
// (ported from OSCURA), and lib/demo/registry.ts, the module map the preview engine runs (ADR 0028).
// `npx convex dev` regenerates api.d.ts identically once a deployment is linked. Run after adding a convex module.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../convex/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const skip = new Set(["schema.ts", "auth.config.ts", "convex.config.ts"]);
const modules = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name !== "_generated" && name !== "__tests__") walk(full);
    } else if (name.endsWith(".ts") && !name.endsWith(".d.ts") && !name.endsWith(".test.ts") && !skip.has(name)) {
      modules.push({ path: relative(root, full).split("\\").join("/").replace(/\.ts$/, ""), node: /^\s*["']use node["']/m.test(readFileSync(full, "utf8")) });
    }
  }
})(root);

const ident = (m) => m.replace(/\//g, "_");
const api = `/* eslint-disable */
/**
 * Generated \`api\` utility.
 *
 * THIS CODE IS AUTOMATICALLY GENERATED.
 *
 * To regenerate, run \`npx convex dev\`.
 * @module
 */

${modules.map(({ path: m }) => `import type * as ${ident(m)} from "../${m}.js";`).join("\n")}

import type {
  ApiFromModules,
  FilterApi,
  FunctionReference,
} from "convex/server";

declare const fullApi: ApiFromModules<{
${modules.map(({ path: m }) => `  ${m.includes("/") ? JSON.stringify(m) : m}: typeof ${ident(m)};`).join("\n")}
}>;

export declare const api: FilterApi<
  typeof fullApi,
  FunctionReference<any, "public">
>;

export declare const internal: FilterApi<
  typeof fullApi,
  FunctionReference<any, "internal">
>;

export declare const components: {};
`;
writeFileSync(join(root, "_generated", "api.d.ts"), api);

// Node actions ("use node") never run in the browser: the preview engine skips them.
const noFunctions = new Set(["crons", "http", "seedData"]);
const browser = modules.filter((m) => !m.node && !m.path.startsWith("lib/") && !noFunctions.has(m.path));
const registry = `// Generated by scripts/gen-convex-api.mjs. Every Convex module the preview engine can run (ADR 0028).
${browser.map(({ path: m }) => `import * as ${ident(m)} from "../../convex/${m}";`).join("\n")}

export const REGISTRY: Record<string, unknown> = {
${browser.map(({ path: m }) => `  ${JSON.stringify(m)}: ${ident(m)},`).join("\n")}
};
`;
writeFileSync(new URL("../lib/demo/registry.ts", import.meta.url), registry);
console.log(`api.d.ts: ${modules.length} modules; registry: ${browser.length}`);
